function join(
  table: Readonly<Record<string, readonly [string, string]>>,
  id: string,
  five: FiveLanguages,
): Record<InterfaceLanguage, string> {
  /* English, never a blank, if a piece somehow has none: the test is what
     keeps this from happening. */
  const [japanese, korean] = table[id] ?? [five.english, five.english];
  return { ...five, japanese, korean };
}

/** A piece's names in all seven interface languages. */
export function sevenNames(id: string, five: FiveLanguages): Record<InterfaceLanguage, string> {
  return join(JA_KO_NAMES, id, five);
}

/** A limited piece's introduction in all seven interface languages. */
export function sevenIntros(id: string, five: FiveLanguages): Record<InterfaceLanguage, string> {
  return join(JA_KO_INTROS, id, five);
}

/** A piece written with five names, as the collections' tables are. */
export type FiveNamedItem<T extends { names: unknown }> = Omit<T, "names"> & { names: FiveLanguages };

/** Gives a five-named piece its Japanese and Korean names. */
export function withSevenNames<T extends { id: string; names: Record<InterfaceLanguage, string> }>(
  item: FiveNamedItem<T>,
): T {
  return { ...item, names: sevenNames(item.id, item.names) } as T;
}
